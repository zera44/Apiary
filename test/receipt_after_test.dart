void main() {
  test('Фудком N304 (фото з нахилом): 5 позицій, суми й кількості', () {
    final rows = parseReceipt(_n304);
    expect(rows.length, 5, reason: rows.toString());
    expect(rows[0].name, startsWith('Пакет-майка'));
    expect(rows[0].qty, 1);
    expect(rows[0].price, 0.5);
    expect(rows[1].name, contains('Порошок'));
    expect(rows[1].qty, closeTo(2.094, 1e-9));
    expect(rows[1].unit, 'кг');
    expect(rows[1].price, 41.18);
    expect(rows[2].name, contains('Head&Shoulders'));
    expect(rows[2].price, 297.99);
    expect(rows[3].name, contains('Гель'));
    expect(rows[4].name, startsWith('Хліб грузинський'));
    expect(rows[4].price, 39.9);
    // шапка й картка - не товари
    expect(rows.any((r) => r.name.contains('Магазин') || r.name.contains('ПРИВАТБАНК')), isFalse);
  });

  test('Фудком N217: 18 позицій, знижки враховано', () {
    final rows = parseReceipt(_n217);
    expect(rows.length, 18, reason: rows.toString());
    expect(rows.first.name, startsWith('Благодійність'));
    expect(rows[1].qty, 60);
    final egg = rows[1];
    expect(egg.qty * egg.price, closeTo(279.35, 0.5)); // 280,20 - знижка 0,85
    final cheese = rows.firstWhere((r) => r.name.startsWith('СирУкраїнський'));
    expect(cheese.qty, closeTo(0.236, 1e-9));
    expect(cheese.qty * cheese.price, closeTo(132.02 - 43.57, 0.5));
    final total = rows.fold<double>(0, (s, r) => s + r.qty * r.price);
    expect(total, closeTo(1944.00, 2.5));
  });
}
