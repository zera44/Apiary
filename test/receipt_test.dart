      addTearDown(() => tester.binding.setSurfaceSize(null));
      final known = (await tester.runAsync(() async {
        final id = await repo.addStockItem('Вощина пасічна', 'шт');
        await repo.receiveStock(id, 10, total: 100);
        return id;
      }))!;
