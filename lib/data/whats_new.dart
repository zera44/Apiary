/// Опис оновлення для екрана «Що нового». Функції — від найзначнішої:
/// одразу видно лише перші 20% (Парето), решта й виправлені помилки — у «Ще».
class Release {
  final String version;
  final List<String> features;
  final List<String> fixes;
  const Release(this.version, this.features, this.fixes);

  int get _top => (features.length * 0.2).round().clamp(1, features.length);
  List<String> get topFeatures => features.take(_top).toList();
  List<String> get moreFeatures => features.skip(_top).toList();
}

